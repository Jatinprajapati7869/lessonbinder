//! Speech-to-text port (whisper.cpp when configured; default disabled).

use std::path::{Path, PathBuf};
use std::process::Command;

use crate::cues::SubtitleCue;
use crate::db::DbError;
use crate::order::learning_order;
use crate::vault_settings::VaultSettings;
use crate::whisper_cpp::{parse_whisper_json_output, resolve_whisper_cpp_binary, whisper_cli_argv};
use crate::VaultDb;

#[derive(Debug, PartialEq, Eq, thiserror::Error)]
pub enum TranscriptionError {
    #[error("transcription_disabled")]
    TranscriptionDisabled,
    #[error("transcription_unavailable")]
    TranscriptionUnavailable,
    #[error("lesson not found")]
    LessonNotFound,
    #[error("lesson media not found")]
    MediaNotFound,
    #[error("database error: {0}")]
    Db(String),
    #[error("whisper: {0}")]
    Whisper(String),
}

impl From<DbError> for TranscriptionError {
    fn from(value: DbError) -> Self {
        TranscriptionError::Db(value.to_string())
    }
}

/// Local transcription backend.
pub trait TranscriptionEngine {
    fn transcribe_lesson(&self, db: &VaultDb, lesson_id: &str) -> Result<(), TranscriptionError>;
}

/// Default engine: transcription is not available.
#[derive(Debug, Clone, Copy, Default)]
pub struct DisabledTranscriptionEngine;

pub fn transcription_disabled() -> DisabledTranscriptionEngine {
    DisabledTranscriptionEngine
}

impl TranscriptionEngine for DisabledTranscriptionEngine {
    fn transcribe_lesson(&self, _db: &VaultDb, _lesson_id: &str) -> Result<(), TranscriptionError> {
        Err(TranscriptionError::TranscriptionDisabled)
    }
}

/// Test adapter that writes predetermined cues without running whisper.cpp.
#[derive(Debug, Clone)]
pub struct FakeTranscriptionEngine {
    cues: Vec<SubtitleCue>,
}

impl FakeTranscriptionEngine {
    pub fn new(cues: Vec<SubtitleCue>) -> Self {
        Self { cues }
    }
}

impl TranscriptionEngine for FakeTranscriptionEngine {
    fn transcribe_lesson(&self, db: &VaultDb, lesson_id: &str) -> Result<(), TranscriptionError> {
        transcribe_with_cues(db, lesson_id, &self.cues)
    }
}

/// whisper.cpp adapter when model path is a file and `whisper-cli` is on PATH.
#[derive(Debug, Clone)]
pub struct WhisperCppTranscriptionEngine {
    binary: PathBuf,
    model_path: PathBuf,
}

impl WhisperCppTranscriptionEngine {
    pub fn new(binary: PathBuf, model_path: PathBuf) -> Self {
        Self { binary, model_path }
    }
}

impl TranscriptionEngine for WhisperCppTranscriptionEngine {
    fn transcribe_lesson(&self, db: &VaultDb, lesson_id: &str) -> Result<(), TranscriptionError> {
        let media = db
            .local_media_path_for_lesson(lesson_id)?
            .ok_or(TranscriptionError::LessonNotFound)?;
        if !media.is_file() {
            return Err(TranscriptionError::MediaNotFound);
        }
        let cues = run_whisper_cli(&self.binary, &self.model_path, &media)?;
        transcribe_with_cues(db, lesson_id, &cues)
    }
}

/// Engine selected from vault settings (empty model → disabled; missing binary/model file → unavailable).
pub enum SettingsTranscriptionEngine {
    Disabled(DisabledTranscriptionEngine),
    Unavailable,
    Whisper(WhisperCppTranscriptionEngine),
}

impl TranscriptionEngine for SettingsTranscriptionEngine {
    fn transcribe_lesson(&self, db: &VaultDb, lesson_id: &str) -> Result<(), TranscriptionError> {
        match self {
            Self::Disabled(engine) => engine.transcribe_lesson(db, lesson_id),
            Self::Unavailable => Err(TranscriptionError::TranscriptionUnavailable),
            Self::Whisper(engine) => engine.transcribe_lesson(db, lesson_id),
        }
    }
}

pub fn transcription_engine_from_settings(
    settings: &VaultSettings,
    whisper_binary: Option<PathBuf>,
) -> SettingsTranscriptionEngine {
    if settings.transcription_model_path.is_empty() {
        return SettingsTranscriptionEngine::Disabled(transcription_disabled());
    }
    let model = PathBuf::from(&settings.transcription_model_path);
    if !model.is_file() {
        return SettingsTranscriptionEngine::Unavailable;
    }
    let binary = whisper_binary.or_else(|| resolve_whisper_cpp_binary().ok());
    let binary = match binary.filter(|path| path.is_file()) {
        Some(path) => path,
        None => return SettingsTranscriptionEngine::Unavailable,
    };
    SettingsTranscriptionEngine::Whisper(WhisperCppTranscriptionEngine::new(binary, model))
}

/// Ordered cues generated by transcription (`source=transcription` in storage).
pub fn list_transcription_cues(
    db: &VaultDb,
    lesson_id: &str,
) -> Result<Vec<SubtitleCue>, TranscriptionError> {
    db.list_lesson_transcription_cues(lesson_id)
        .map_err(|e| TranscriptionError::Db(e.to_string()))
}

pub fn run_lesson_transcription(
    db: &VaultDb,
    lesson_id: &str,
    engine: &impl TranscriptionEngine,
) -> Result<(), TranscriptionError> {
    engine.transcribe_lesson(db, lesson_id)
}

fn transcribe_with_cues(
    db: &VaultDb,
    lesson_id: &str,
    cues: &[SubtitleCue],
) -> Result<(), TranscriptionError> {
    let course_id = db
        .course_id_for_lesson(lesson_id)?
        .ok_or(TranscriptionError::LessonNotFound)?;
    let order_before = learning_order(db, &course_id)?;
    let progress_before = db.progress_for_lesson(lesson_id)?;

    db.replace_lesson_transcription_cues(lesson_id, cues)?;

    if learning_order(db, &course_id)? != order_before {
        db.replace_lesson_transcription_cues(lesson_id, &[])?;
        return Err(TranscriptionError::Db(
            "lesson order changed during transcription".into(),
        ));
    }
    if db.progress_for_lesson(lesson_id)? != progress_before {
        db.replace_lesson_transcription_cues(lesson_id, &[])?;
        return Err(TranscriptionError::Db(
            "lesson progress changed during transcription".into(),
        ));
    }
    Ok(())
}

fn run_whisper_cli(
    binary: &Path,
    model_path: &Path,
    media_path: &Path,
) -> Result<Vec<SubtitleCue>, TranscriptionError> {
    let temp_dir = tempfile::tempdir().map_err(|e| TranscriptionError::Whisper(e.to_string()))?;
    let output_prefix = temp_dir.path().join("out");
    let argv = whisper_cli_argv(binary, model_path, media_path, &output_prefix);
    let program = argv
        .first()
        .ok_or_else(|| TranscriptionError::Whisper("empty whisper argv".into()))?;
    let args: Vec<&str> = argv[1..].iter().map(String::as_str).collect();
    let status = Command::new(program)
        .args(args)
        .status()
        .map_err(map_whisper_err)?;
    if !status.success() {
        return Err(TranscriptionError::Whisper(format!(
            "whisper-cli exited with {}",
            status
        )));
    }
    let json_path = output_prefix.with_extension("json");
    let text = std::fs::read_to_string(&json_path).map_err(map_whisper_err)?;
    parse_whisper_json_output(&text).map_err(|e| TranscriptionError::Whisper(e.to_string()))
}

fn map_whisper_err(err: std::io::Error) -> TranscriptionError {
    TranscriptionError::Whisper(err.to_string())
}
